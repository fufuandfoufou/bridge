// DeepSeek Harness has no shell hooks. Connecting it adds rows to the
// harness's home-level loader patch ($DSH_HOME/cordis.patch.yml):
//
//   - an MCP client for `bridge mcp`, so the model can query other agents;
//   - for plugin-verified versions, a small plugin that adds other agents'
//     progress to each step's runtime context through `bridge hook`.
//
// The rows live in a marked block; the rest of the file is the user's and is
// never touched. Whether progress is actually injected is decided per turn by
// the daemon (agents.dsh.inject, off by default), because dsh uploads its
// session logs unless the user turns that off.

const (
	patchBegin = "# bridge:begin (managed by bridge; removed by bridge uninstall)"
	patchEnd   = "# bridge:end"
)

// pluginVersions are the releases whose plugin API the live plugin was
// verified against (systemPrompt.context with the agent's session).
var pluginVersions = map[string]bool{"0.2.2-rc.1": true}

func patchPath() string  { return filepath.Join(Home(), "cordis.patch.yml") }
func pluginPath() string { return filepath.Join(fsutil.DataDir(), "dsh", "bridge-live.mjs") }

func yamlString(s string) string {
	b, _ := json.Marshal(s) // JSON strings are valid YAML double-quoted scalars
	return string(b)
}

func renderBlock(command string, plugin bool) string {
	var b strings.Builder
	b.WriteString(patchBegin + "\n- insert:\n")
	fmt.Fprintf(&b, "    - id: bridge-mcp\n      name: '@deepseek-ai/dsh-mcp-client'\n      config:\n        serverName: bridge\n        transport: stdio\n        command: %s\n        args: [\"mcp\"]\n", yamlString(command))
	if plugin {
		fmt.Fprintf(&b, "    - id: bridge-live\n      name: %s\n", yamlString(pluginPath()))
	}
	b.WriteString(patchEnd + "\n")
	return b.String()
}

// stripBlock removes bridge's block and reports whether one was present.
func stripBlock(text string) (string, bool) {
	i := strings.Index(text, patchBegin)
	if i < 0 {
		return text, false
	}
	j := strings.Index(text[i:], patchEnd)
	if j < 0 {
		return text, false
	}
	end := i + j + len(patchEnd)
	if end < len(text) && text[end] == '\n' {
		end++
	}
	return text[:i] + text[end:], true
}

// onlyEmptyList reports whether the YAML holds nothing but comments and an
// empty flow sequence "[]", the form dsh writes for an empty patch layer.
func onlyEmptyList(text string) (bool, bool) {
	hasList := false
	for _, l := range strings.Split(text, "\n") {
		t := strings.TrimSpace(l)
		switch {
		case t == "" || strings.HasPrefix(t, "#"):
		case t == "[]":
			hasList = true
		default:
			return false, hasList
		}
	}
	return true, hasList
}

// withBlock returns the patch file with bridge's block (re)placed.
func withBlock(text, block string) (string, error) {
	text, _ = stripBlock(text)
	empty, hasList := onlyEmptyList(text)
	if empty {
		if hasList { // an empty flow list can't be followed by block items
			var kept []string
			for _, l := range strings.Split(text, "\n") {
				if strings.TrimSpace(l) != "[]" {
					kept = append(kept, l)
				}
			}
			text = strings.Join(kept, "\n")
		}
		text = strings.TrimRight(text, "\n")
		if text != "" {
			text += "\n"
		}
		return text + block, nil
	}
	for _, l := range strings.Split(text, "\n") {
		t := strings.TrimSpace(l)
		if t != "" && !strings.HasPrefix(t, "#") && !strings.HasPrefix(l, "-") && !strings.HasPrefix(l, " ") {
			return "", fmt.Errorf("%s is not a block-style YAML list; add bridge's rows by hand or rewrite it as one", patchPath())
		}
	}
	return strings.TrimRight(text, "\n") + "\n" + block, nil
}

// withoutBlock removes bridge's block; an emptied file keeps the "[]" dsh
// requires, since an empty or comments-only patch file fails its boot.
func withoutBlock(text string) string {
	text, _ = stripBlock(text)
	if empty, hasList := onlyEmptyList(text); empty && !hasList {
		text = strings.TrimRight(text, "\n")
		if text != "" {
			text += "\n"
		}
		text += "[]\n"
	}
	return text
}

func renderPlugin(command string) string {
	return `// bridge:managed plugin (generated by bridge; removed by bridge uninstall)
// Adds other coding agents' progress to each DeepSeek Harness step as runtime
// context, via ` + "`bridge hook`" + `. The bridge daemon decides whether anything is
// injected (agents.dsh.inject).
import { execFileSync } from 'node:child_process'

export const name = 'bridge-live'
export const inject = ['systemPrompt']

const BRIDGE = ` + yamlString(command) + `
// Runtime context may be evaluated more than once per step; a delivered
// digest is acknowledged, so it is cached briefly instead of re-asked.
const TTL_MS = 20000
const cache = new Map()
const started = new Set()

function ask(event, payload) {
  try {
    const out = execFileSync(BRIDGE, ['hook', event, '--agent', 'dsh'], {
      input: JSON.stringify(payload), timeout: 1500, encoding: 'utf8', stdio: ['pipe', 'pipe', 'ignore'],
    })
    return JSON.parse(out || '{}')?.hookSpecificOutput?.additionalContext ?? ''
  } catch {
    return ''
  }
}

function progress(session) {
  const id = session?.id
  const cwd = session?.header?.cwd
  if (typeof id !== 'string' || typeof cwd !== 'string') return ''
  const hit = cache.get(id)
  if (hit && Date.now() - hit.at < TTL_MS) return hit.text
  const parts = []
  if (!started.has(id)) {
    started.add(id)
    parts.push(ask('session_start', { session_id: id, cwd }))
  }
  parts.push(ask('prompt_submit', { session_id: id, cwd }))
  const text = parts.filter((s) => s).join('\n\n')
  cache.set(id, { at: Date.now(), text })
  return text
}

export function apply(ctx) {
  ctx.systemPrompt.context({
    name: 'bridge:progress',
    order: 300,
    interpolate: false,
    text: (context) => progress(context.agent?.session),
  })
}
`
}

// InstallHooks implements Adapter.
func (a *Adapter) InstallHooks(ctx context.Context, cfg kit.HookConfig) error {
	if len(cfg.MCPCommand) == 0 && cfg.Command == "" {
		return nil
	}
	bin := cfg.Command
	if bin == "" {
		bin = cfg.MCPCommand[0]
	}
	in, err := a.Detect(ctx)
	if err != nil {
		return err
	}
	plugin := pluginVersions[string(in.Version)] && cfg.Command != ""
	if plugin {
		if err := os.MkdirAll(filepath.Dir(pluginPath()), 0o700); err != nil {
			return err
		}
		if err := fsutil.AtomicWrite(pluginPath(), []byte(renderPlugin(cfg.Command)), 0o644); err != nil {
			return err
		}
	}
	b, err := os.ReadFile(patchPath())
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	text, err := withBlock(string(b), renderBlock(bin, plugin))
	if err != nil {
		return err
	}
	if text == string(b) {
		return nil
	}
	if err := os.MkdirAll(Home(), 0o755); err != nil {
		return err
	}
	return fsutil.SafeWrite(patchPath(), []byte(text), 0o644)
}

// UninstallHooks implements Adapter.
func (a *Adapter) UninstallHooks(ctx context.Context) error {
	if b, err := os.ReadFile(patchPath()); err == nil {
		if _, ok := stripBlock(string(b)); ok {
			if err := fsutil.SafeWrite(patchPath(), []byte(withoutBlock(string(b))), 0o644); err != nil {
				return err
			}
		}
	} else if !errors.Is(err, os.ErrNotExist) {
		return err
	}
	if err := os.Remove(pluginPath()); err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	return nil
}

// HooksInstalled implements adapterkit.HookChecker: bridge's rows are in the
// harness's patch file.
func (a *Adapter) HooksInstalled() bool {
	b, err := os.ReadFile(patchPath())
	if err != nil {
		return false
	}
	_, ok := stripBlock(string(b))
	return ok
}

// pluginHooks are the lifecycle points the live plugin covers for a version.
func pluginHooks(v kit.Version) []kit.HookKind {
	if pluginVersions[string(v)] {
		return []kit.HookKind{kit.HookSessionStart, kit.HookPromptSubmit}
	}
	return nil
}
