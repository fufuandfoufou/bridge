package pi

import (
	"bytes"
	"encoding/json"
	"os"
	"path/filepath"
	"strings"
	"text/template"

	"bridge/internal/fsutil"
)

// pi has no shell hooks, but its extensions see the same lifecycle. Bridge
// installs one extension that forwards each event to `bridge hook`, so pi
// gets the same live progress, memory and file claims as Claude Code and
// Codex, through the same daemon logic and delivery acknowledgements.

// extensionMarker identifies the file bridge owns.
const extensionMarker = "// bridge:managed extension (generated by bridge; removed by bridge uninstall)"

func extensionPath() string { return filepath.Join(Root(), "extensions", "bridge.js") }

var extensionTmpl = template.Must(template.New("ext").Parse(extensionMarker + `
// Forwards pi's lifecycle to Bridge so pi shares progress, memory and file
// claims with the other coding agents. Bridge regenerates this file.
import { execFile } from "node:child_process";

const BRIDGE = {{.Command}};
const TIMEOUT_MS = 2000;

function hook(event, ctx, extra = {}) {
  const payload = JSON.stringify({
    session_id: ctx.sessionManager.getSessionId(),
    cwd: ctx.sessionManager.getCwd?.() ?? ctx.cwd,
    ...extra,
  });
  return new Promise((resolve) => {
    const child = execFile(BRIDGE, ["hook", event, "--agent", "pi"], { timeout: TIMEOUT_MS }, (err, stdout) => {
      if (err || !stdout) return resolve({});
      try {
        resolve(JSON.parse(stdout).hookSpecificOutput ?? {});
      } catch {
        resolve({});
      }
    });
    child.stdin?.end(payload);
  });
}

export default function bridge(pi) {
  let startContext = "";
  const warnings = new Map();

  pi.on("session_start", async (_event, ctx) => {
    const out = await hook("session_start", ctx);
    startContext = out.additionalContext ?? "";
  });

  pi.on("before_agent_start", async (event, ctx) => {
    if (event.messageType !== "user") return;
    const out = await hook("prompt_submit", ctx);
    const parts = [startContext, out.additionalContext ?? ""].filter((s) => s);
    startContext = "";
    if (parts.length === 0) return;
    return { message: { customType: "bridge", content: parts.join("\n\n"), display: false } };
  });

  pi.on("tool_call", async (event, ctx) => {
    const out = await hook("pre_tool", ctx, { tool_name: event.toolName, tool_input: event.input });
    if (out.permissionDecision === "deny") {
      return { block: true, reason: out.permissionDecisionReason ?? "blocked by Bridge" };
    }
    if (out.additionalContext) warnings.set(event.toolCallId, out.additionalContext);
  });

  pi.on("tool_result", async (event, ctx) => {
    await hook("post_tool", ctx, { tool_name: event.toolName, tool_input: event.input });
    const warning = warnings.get(event.toolCallId);
    if (!warning) return;
    warnings.delete(event.toolCallId);
    return { content: [...(event.content ?? []), { type: "text", text: warning }] };
  });

  pi.on("session_shutdown", async (_event, ctx) => {
    await hook("stop", ctx);
  });
}
`))

func renderExtension(command string) ([]byte, error) {
	q, err := json.Marshal(command)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	err = extensionTmpl.Execute(&b, map[string]string{"Command": string(q)})
	return b.Bytes(), err
}

func installExtension(command string) error {
	data, err := renderExtension(command)
	if err != nil {
		return err
	}
	p := extensionPath()
	if b, err := os.ReadFile(p); err == nil {
		if !strings.HasPrefix(string(b), extensionMarker) {
			return os.ErrExist // a file of the user's own with our name
		}
		if bytes.Equal(b, data) {
			return nil
		}
	}
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return err
	}
	return fsutil.SafeWrite(p, data, 0o644)
}

func removeExtension() error {
	b, err := os.ReadFile(extensionPath())
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	if !strings.HasPrefix(string(b), extensionMarker) {
		return nil // not ours
	}
	return os.Remove(extensionPath())
}

func extensionInstalled() bool {
	b, err := os.ReadFile(extensionPath())
	return err == nil && strings.HasPrefix(string(b), extensionMarker)
}
